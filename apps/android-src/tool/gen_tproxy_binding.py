#!/usr/bin/env python3
"""Writes the Java binding hev-socks5-tunnel's JNI_OnLoad registers its natives on.

RegisterNatives fails unless every method in hev-jni.c's table exists on the Java class with
the exact same signature, and those signatures have changed between hev releases (void vs
boolean returns, an added TProxyIsRunning). Generating the class from the very source being
built means the two can never drift apart.

usage: gen_tproxy_binding.py <path/to/hev-socks5-tunnel/src/hev-jni.c> <output TProxyService.java>
"""
import re
import sys

JAVA = {"V": "void", "Z": "boolean", "I": "int", "J": "long", "B": "byte",
        "S": "short", "C": "char", "F": "float", "D": "double"}


def parse_types(sig):
    out, i = [], 0
    while i < len(sig):
        dims = 0
        while sig[i] == "[":
            dims += 1
            i += 1
        if sig[i] == "L":
            end = sig.index(";", i)
            cls = sig[i + 1:end].replace("/", ".")
            t = "String" if cls == "java.lang.String" else cls
            i = end + 1
        else:
            t = JAVA[sig[i]]
            i += 1
        out.append(t + "[]" * dims)
    return out


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    if "PKGNAME" in src and not re.search(r"#\s*ifndef\s+PKGNAME", src):
        m = re.search(r"#\s*define\s+PKGNAME\s+(\S+)", src)
        if m and m.group(1).strip('"') != "hev/htproxy":
            sys.exit(f"hev-jni.c hard-codes PKGNAME {m.group(1)}; expected hev/htproxy")
    methods = re.findall(r'\{\s*"(\w+)"\s*,\s*"\(([^)]*)\)([^"]+)"', src)
    if not methods:
        sys.exit("no JNINativeMethod entries found in " + sys.argv[1])
    lines = [
        "package hev.htproxy;",
        "",
        "/** Generated by gui/tool/gen_tproxy_binding.py from hev-jni.c. Do not edit. */",
        "public final class TProxyService {",
        "    private TProxyService() {}",
        "",
    ]
    for name, params, ret in methods:
        types = parse_types(params)
        args = ", ".join(f"{t} a{i}" for i, t in enumerate(types))
        lines.append(f"    public static native {parse_types(ret)[0]} {name}({args});")
    lines.append("}")
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("binding:", ", ".join(m[0] for m in methods))


if __name__ == "__main__":
    main()
